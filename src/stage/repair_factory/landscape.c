// 0x0800da04
static void LayerUpdate_2(struct StageLayer* l, const struct Stage* stage) {
  s32 chunkX;

  if (l->phase == 0) {
    const u16 n = l->bgIdx;
    BGCNT16(n >> 4) = (BGCNT16(n >> 4) & 0xFFFC) | BGCNT_PRIORITY(2);
    (l->scrollPower).x = 0xC0;
    (l->scrollPower).y = 0xC0;
    l->phase++;
  }

  chunkX = gScreenX[(l->viewportLeftTopPixel).x >> 4];
  if (chunkX < 6) {
    (l->scrollPower).y = 0x100;
    (l->scroll).x = 120;
  } else if (chunkX < 17) {
    (l->scroll).x = 960;
    (l->scroll).y = 200;
  } else if (chunkX < 20) {
    (l->scroll).x = 1080;
    (l->scroll).y = 140;
  } else {
    (l->scroll).x = 1752;
    (l->scroll).y = 200;
  }
}

// 0x0800da80
static void LayerUpdate_3(struct StageLayer* l, const struct Stage* stage) {
  s32 x = gScreenX[(l->viewportLeftTopPixel).x >> 4];
  if (x < 6) {
    (l->scrollPower).x = 0x40;
    (l->scrollPower).y = 0x100;
    (l->scroll).x = 360;
  } else if (x < 15) {
    (l->scroll).x = 1560;
    (l->scroll).y = 320;
  } else if (x < 17) {
    (l->scroll).x = 1920;
    (l->scroll).y = 400;
  } else if (x < 20) {
    (l->scroll).x = 2160;
    (l->scroll).y = 280;
  } else if (x < 28) {
    (l->scroll).x = 3000;
    (l->scroll).y = 400;
  } else {
    (l->scroll).x = 3504;
    (l->scroll).y = 400;
  }
}

