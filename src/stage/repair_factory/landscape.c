// 0x0800DAEC
bool16 FUN_0800daec(s32 x, s32 y) {
  if (x >= PIXEL(1680) && x < PIXEL(1680 + 480)) {
    if (y >= PIXEL(640) && y < PIXEL(960)) {
      struct Overworld* ow = &gOverworld;
      if (GET_METATILE(&ow->terrain, x >> 12, y >> 12) != GET_METATILE(&ow->terrain, x >> 12, (y - PIXEL(640)) >> 12)) {
        Coords32 c = {x, y};
        if (x < PIXEL(1680 + 240)) {
          LoadChunk(7, 4, 54);
        } else {
          LoadChunk(8, 4, 55);
        }
        AppendQuake(8, &c);
        return TRUE;
      }
    }
  }
  return FALSE;
}

